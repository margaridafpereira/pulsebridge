def placeholders(text):
    names = []
    for m in re.finditer(r'\{(\w+)(?:\}|,\s*plural)', text):
        if m.group(1) not in names:
            names.append(m.group(1))
    return names


def main():
    keys = [k for k, *_ in S]
    dupes = {k for k in keys if keys.count(k) > 1}
    assert not dupes, f'duplicate keys: {dupes}'
    en = {'@@locale': 'en'}
    pt = {'@@locale': 'pt'}
    for key, e, p in S:
        assert placeholders(e) == placeholders(p) or set(placeholders(e)) == set(placeholders(p)), key
        en[key] = e
        pt[key] = p
        names = placeholders(e)
        if names:
            en['@' + key] = {'placeholders': {n: {'type': 'int' if n in INTS else 'String'} for n in names}}
    out = Path('lib/l10n')
    out.mkdir(parents=True, exist_ok=True)
    (out / 'app_en.arb').write_text(json.dumps(en, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    (out / 'app_pt.arb').write_text(json.dumps(pt, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'{len(S)} strings')


if __name__ == '__main__':
    main()
